def translate_otui(text):
    def tr_text(m):
        key, val = m.group(1), m.group(2)
        return f"{key}: {PT.get(val.strip(), val)}" if val.strip() in PT else m.group(0)

    text = re.sub(r"(?m)^(\s*(?:text|tooltip|placeholder)): (.+?)\s*$",
                  lambda m: f"{m.group(1)}: {PT[m.group(2)]}" if m.group(2) in PT else m.group(0), text)
    text = re.sub(r"tr\('([^']*)'\)", lambda m: "tr('%s')" % PT[m.group(1)].replace("'", "\\'") if m.group(1) in PT else m.group(0), text)
    return text


def main():
    files = glob.glob(os.path.join(ROOT, "default_configs", "Thyrania", "vBot", "*.otui")) + [os.path.join(ROOT, "bot.otui")]
    changed = 0
    for f in files:
        src = open(f, encoding="utf-8").read()
        out = translate_otui(src)
        if out != src:
            open(f, "w", encoding="utf-8").write(out)
            changed += 1
    print(f"{changed} arquivos .otui traduzidos")


if __name__ == "__main__":
    main()
